#!/usr/bin/env python3
"""Generate or check the shared Khaam HyperFrames CSS tokens from one JSON source.

Usage:
  python sync_motion_tokens.py <project>/motion-tokens.json
  python sync_motion_tokens.py <project>/motion-tokens.json --check

The generated CSS is replaceable only when it carries this tool's marker. No
packages, fonts, network access, or other project files are touched.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
from pathlib import Path
from typing import Any

MARKER = "/* Generated by scripts/sync_motion_tokens.py from motion-tokens.json. */"
TOKEN_NAMES = ("bg", "ink", "accent")
COLOR_RE = re.compile(r"^#[0-9a-fA-F]{6}$")


class TokenError(ValueError):
    pass


def load_tokens(path: Path) -> dict[str, str]:
    if path.is_symlink() or not path.is_file():
        raise TokenError(f"Token source is missing or is a symlink: {path}")
    try:
        data = json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, json.JSONDecodeError) as exc:
        raise TokenError(f"Cannot read token JSON: {exc}") from exc
    if not isinstance(data, dict) or data.get("version") != 1 or not isinstance(data.get("tokens"), dict):
        raise TokenError("Expected version 1 and a tokens object.")
    tokens: dict[str, str] = {}
    for name in TOKEN_NAMES:
        value = data["tokens"].get(name)
        if not isinstance(value, str) or not COLOR_RE.fullmatch(value):
            raise TokenError(f"tokens.{name} must be a six-digit hexadecimal color (for example #112233).")
        tokens[name] = value.lower()
    extra = sorted(set(data["tokens"]) - set(TOKEN_NAMES))
    if extra:
        raise TokenError("Unsupported token name(s): " + ", ".join(extra))
    return tokens


def render_css(tokens: dict[str, str]) -> str:
    return "\n".join([
        MARKER,
        ":root {",
        *(f"  --{name}: {tokens[name]};" for name in TOKEN_NAMES),
        "}",
        "",
    ])


def sync(source: Path, output: Path, *, check: bool = False) -> bool:
    source = source.expanduser().resolve()
    output = output.expanduser()
    tokens = load_tokens(source)
    expected = render_css(tokens)
    if output.is_symlink():
        raise TokenError(f"Refusing to follow a CSS symlink: {output}")
    if check:
        if not output.is_file() or output.read_text(encoding="utf-8") != expected:
            raise TokenError(f"Generated CSS is missing or stale: {output}")
        return True
    if output.exists():
        current = output.read_text(encoding="utf-8")
        if MARKER not in current:
            raise TokenError(f"Refusing to overwrite CSS without this tool's generated-file marker: {output}")
    output.parent.mkdir(parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(prefix=".motion-tokens-", suffix=".tmp", dir=output.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(expected)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temp_name, output)
    except Exception:
        try:
            os.unlink(temp_name)
        except OSError:
            pass
        raise
    return False


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", help="motion-tokens.json")
    parser.add_argument("--out", help="generated CSS path (default: next to the JSON file)")
    parser.add_argument("--check", action="store_true", help="fail if generated CSS is missing or stale; write nothing")
    args = parser.parse_args(argv)
    source = Path(args.source)
    output = Path(args.out) if args.out else source.with_name("motion-tokens.css")
    try:
        was_current = sync(source, output, check=args.check)
    except (TokenError, OSError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    print(f"Shared motion tokens {'verified' if args.check or was_current else 'generated'}: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
